/* Builds js/skystars.js, the naked-eye stars the sky-photo page matches a photo against,
 * from what tools/skystars/fetch.py saved in raw/ (NOTES.md, "Sky photos"). No request.
 *
 *   node tools/skystars/build.mjs
 *
 * Positions are Hipparcos's (ICRS, epoch J1991.25), not moved for proper motion: by 2026
 * the fastest of these stars has gone a few arcseconds to a few arcminutes, under a pixel
 * of a phone photo shrunk to 1,600 px except for a handful (61 Cygni, 0.05 degrees).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bestName } from '../../js/starnames.js';

const here = dirname(fileURLToPath(import.meta.url));
const raw = join(here, 'raw');

const idents = new Map();
for (const line of readFileSync(join(raw, 'hip-names.csv'), 'utf8').split('\n').slice(1)) {
    const m = /^"HIP (\d+)","(.*)"\s*$/.exec(line);
    if (!m) continue;
    if (!idents.has(m[1])) idents.set(m[1], []);
    idents.get(m[1]).push(m[2]);
}

const stars = [];
for (const line of readFileSync(join(raw, 'hip-bright.tsv'), 'utf8').split('\n')) {
    const f = line.split('\t').map((s) => s.trim());
    if (f.length < 6 || !/^\d+$/.test(f[0]) || f[1] === '' || f[5] === '') continue;
    stars.push({ hip: Number(f[0]), ra: Number(f[1]), dec: Number(f[2]), v: Number(f[5]) });
}
stars.sort((a, b) => a.v - b.v);

const flat = [];
const names = {};
let named = 0;
for (const s of stars) {
    flat.push(s.hip, Math.round(s.ra * 1000), Math.round(s.dec * 1000), Math.round(s.v * 100));
    const name = bestName(idents.get(String(s.hip)) ?? []);
    if (name) { names[s.hip] = name; named++; }
}

const text = `/* Generated by tools/skystars/build.mjs from tools/skystars/raw/ - never edit by hand.
 * The naked-eye stars, brightest first, for matching sky photos (js/skysolve.js): every
 * Hipparcos star brighter than V 6.5 (ESA 1997, VizieR I/239), and the friendliest name
 * SIMBAD gives each (Wenger et al. 2000; IDIA mirror, data to 2026-10-14).
 * STARS is flat: HIP, RA and Dec (ICRS, thousandths of a degree), V (hundredths). */
export const STAR_COUNT = ${stars.length};
export const STARS = [${flat.join(',')}];
export const STAR_NAMES = ${JSON.stringify(names)};
`;
writeFileSync(join(here, '..', '..', 'js', 'skystars.js'), text);
console.log(`${stars.length} stars, ${named} named, ${(text.length / 1000).toFixed(0)} KB`);
