/* Writes js/spacecrafttracks.js, the tracks built into the site, from what
 * tools/spacecraft/fetch.mjs saved in raw/:
 *
 *   npm run spacecraft
 *
 * The fitting is js/spacecraftfit.js, shared with the collector. Makes no request.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CRAFT } from '../../js/spacecraft.js';
import { buildTrack } from '../../js/spacecraftfit.js';
import { SPAN_START } from './span.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const raw = join(here, 'raw');
const outPath = join(here, '..', '..', 'js', 'spacecrafttracks.js');
const todayJd = Date.now() / 86400000 + 2440587.5;

const lines = [];
for (const craft of CRAFT.filter((s) => s.horizons)) {
    const file = join(raw, `${craft.id}.json`);
    if (!existsSync(file)) { lines.push(`    // ${craft.name}: not fetched`); console.error(`${craft.name}: no file`); continue; }
    const saved = JSON.parse(readFileSync(file, 'utf8'));
    const track = buildTrack(saved, { spanStart: SPAN_START, todayJd });
    if (!track) { lines.push(`    // ${craft.name}: no track fits`); console.error(`${craft.name}: no fit`); continue; }
    const kind = track.elements ? (track.lastKnown ? `last known orbit, ${track.lastKnown}` : 'orbit') : `${track.xyz.length / 3} positions, every ${track.step} days`;
    console.error(`${craft.name}: ${kind}`);
    lines.push(`    ${craft.id}: ${JSON.stringify(track)}, // ${craft.name}: Horizons ${saved.horizons}, fetched ${saved.fetched}, ${saved.start} to ${saved.stop}`);
}
const earthFile = join(raw, 'earth-orbit.json');
const earth = existsSync(earthFile) ? JSON.parse(readFileSync(earthFile, 'utf8')) : { active: 0, inactive: 0, source: '', date: '' };

writeFileSync(outPath, `/* Generated by npm run spacecraft (tools/spacecraft/build.mjs) from what
 * tools/spacecraft/fetch.mjs saved from JPL Horizons and CelesTrak. Do not edit by hand.
 * The tracks built into the site; the collector's monthly ones in rubin-data's
 * spacecraft.json are used over these where the page can reach them. Each free-flying
 * craft's track, heliocentric ecliptic J2000 (AU): an orbit (elements, in the form
 * js/orbit.js takes, valid from \`from\`), or positions every \`step\` days from \`start\`
 * (Julian dates), x, y, z in turn. */
export const TRACKS_FETCHED = '${new Date().toISOString().slice(0, 10)}';

export const TRACKS = {
${lines.join('\n')}
};

/* Payloads still in orbit about Earth, from ${earth.source || 'nowhere yet'} on ${earth.date || '-'}. */
export const EARTH_ORBIT = ${JSON.stringify({ active: earth.active, inactive: earth.inactive, source: earth.source, date: earth.date })};
`);
console.error(`Wrote ${outPath}`);
